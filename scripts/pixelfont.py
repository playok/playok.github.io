_ESCAPES = (("&", "&amp;"), ("<", "&lt;"), (">", "&gt;"), ('"', "&quot;"))


def esc(s):
    for a, b in _ESCAPES:
        s = s.replace(a, b)
    return s


def text_width(text, px, gap=1):
    if not text:
        return 0
    return len(text) * 5 * px + (len(text) - 1) * gap * px


def text_rects(text, x, y, px, color, gap=1):
    """가로로 연속된 픽셀은 하나의 rect로 합쳐 출력 크기를 줄인다."""
    out = []
    cursor = x
    for ch in text.upper():
        rows = GLYPHS.get(ch, GLYPHS[" "])
        for ry, row in enumerate(rows):
            rx = 0
            while rx < 5:
                if row[rx] == "#":
                    run = 1
                    while rx + run < 5 and row[rx + run] == "#":
                        run += 1
                    out.append(
                        f'<rect x="{cursor + rx * px}" y="{y + ry * px}" '
                        f'width="{run * px}" height="{px}" fill="{color}"/>'
                    )
                    rx += run
                else:
                    rx += 1
        cursor += (5 + gap) * px
    return "".join(out)


def svg_header(w, h):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
        f'viewBox="0 0 {w} {h}" role="img">'
    )


def svg_footer():
    return "</svg>\n"


def scanlines(w, h, opacity=0.18):
    return "".join(
        f'<rect x="0" y="{y}" width="{w}" height="1" fill="#000" opacity="{opacity}"/>'
        for y in range(0, h, 2)
    )
